/** 标题块：整部剧本的第一段 */
export function renderTitleBlock({ title, totalEpisodes = 40, genre = '都市重生复仇', source = '参考文档规范' } = {}) {
  return [
    `# AI短剧《${title}》${totalEpisodes}集原创剧本`,
    `> 格式完全沿用${source}：【故事梗概】【人物小传】前置；单集：场号‑序号 时间 内外景 场景名，出场人物；△镜头/动作描写；人物台词；OS内心独白；【闪回】【闪出】；音效标注。`,
    `> 题材：${genre}，单集60‑90秒，适配AI漫剧、数字人短剧批量生成`,
  ].join('\n');
}

/** 人物小传块：characters = [{name, role, desc}] */
export function renderCastBlock(characters = []) {
  const lines = ['## 【人物小传】'];
  for (const c of characters) {
    lines.push(`**${c.name}｜${c.role || '配角'}**`);
    lines.push(c.desc || '（待补充）');
    lines.push('');
  }
  return lines.join('\n').trim();
}
